#!/usr/bin/env python3
"""Extract the radio constants the BT libraries need from the SDK's wifi_conf.c, the branch the SDK
builds (the #else of its "WIFI RX" strategy switch), into shim/rf_const.c.
  tools_rfconst.py ~/fw-AC79_AIoT_SDK > shim/rf_const.c"""
import sys, re
src = open(sys.argv[1] + "/apps/common/net/wifi_conf.c", encoding="utf-8", errors="replace").read().split("\n")
start = next(i for i, l in enumerate(src) if i > 1200 and "#else" in l and "WIFI RX" in l)
end = start + 1 + next(i for i, l in enumerate(src[start + 1:]) if l.startswith("#endif"))
body = "\n".join(src[start + 1:end])
body = re.sub(r"//[^\n]*", "", body)
out = ["/* Generated by tools_rfconst.py from the JieLi AC79 SDK (Apache-2.0), apps/common/net/wifi_conf.c:",
       " * the radio's tuning constants and its RAM lookup table, the branch the SDK builds. */",
       "#include <stdint.h>", "typedef uint8_t u8; typedef uint32_t u32;",
       "const u8 RTDebugLevel = 2;", "const char WIFI_PA_ENABLE = 0;", "const char wifi_temperature_drift_trim_on = 0;",
       "const u8 RFIinitUseTrimValue = 1;", body]
print("\n".join(out))
